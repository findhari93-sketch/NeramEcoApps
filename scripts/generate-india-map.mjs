#!/usr/bin/env node
/**
 * Builds apps/admin/src/components/chat-history/india-state-paths.ts: one
 * pre-projected SVG path per Indian state / UT, keyed by @neram/geo slugs.
 *
 * Pre-projecting keeps d3-geo, topojson and 17 MB of shapes out of the admin
 * bundle; the page ships about 100 KB of path strings and draws them as-is.
 *
 * Source: DataMeet India "States/Admin2" (Ladakh and J&K as per the Survey of
 * India map, updated 2021), CC BY 4.0, https://github.com/datameet/maps.
 * The map must show India's official boundary, so do not swap the source for
 * a generic world dataset.
 *
 * The tools are not repo dependencies. Run from a scratch folder:
 *   npm i shapefile@0.6.6 d3-geo@3.1.1 topojson-server@3.0.1 topojson-simplify@3.0.3 topojson-client@3.1.0
 *   node <repo>/scripts/generate-india-map.mjs <Admin2.shp> <Admin2.dbf> <out.ts>
 */

import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Resolve the tools from the folder the script is run in, not from the repo.
const require = createRequire(join(process.cwd(), 'noop.js'));
const shapefile = require('shapefile');
const { geoMercator, geoPath } = require('d3-geo');
const { topology } = require('topojson-server');
const { presimplify, simplify } = require('topojson-simplify');
const { feature } = require('topojson-client');

const [shpPath, dbfPath, outPath] = process.argv.slice(2);
if (!shpPath || !dbfPath || !outPath) {
  console.error('usage: generate-india-map.mjs <Admin2.shp> <Admin2.dbf> <out.ts>');
  process.exit(1);
}

const WIDTH = 600;
const HEIGHT = 680;
/** Drop any point whose triangle covers less than this many square pixels. */
const MIN_AREA_PX = 0.6;

/** DataMeet's ST_NM spellings that differ from @neram/geo STATES slugs. */
const SLUG_FOR = {
  'Andaman & Nicobar': 'andaman-and-nicobar',
  'Jammu & Kashmir': 'jammu-and-kashmir',
  'Dadra and Nagar Haveli and Daman and Diu': 'dadra-and-nagar-haveli-and-daman-and-diu',
};
const slugOf = (name) =>
  SLUG_FOR[name] ??
  name.toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const collection = await shapefile.read(shpPath, dbfPath);
for (const f of collection.features) f.properties = { slug: slugOf(f.properties.ST_NM) };

// Project to pixels first, then simplify in flat space. Simplifying on the
// sphere and projecting after lets a thinned ring flip its winding, which d3
// then draws as "the whole globe minus this state".
const projection = geoMercator().fitExtent(
  [
    [8, 8],
    [WIDTH - 8, HEIGHT - 8],
  ],
  collection
);
const projectRing = (ring) => ring.map(([lon, lat]) => projection([lon, lat]));
for (const f of collection.features) {
  const g = f.geometry;
  if (g.type === 'Polygon') g.coordinates = g.coordinates.map(projectRing);
  else if (g.type === 'MultiPolygon') g.coordinates = g.coordinates.map((poly) => poly.map(projectRing));
}

// A shared topology keeps a common edge between neighbouring states.
let topo = topology({ states: collection }, 1e5);
topo = presimplify(topo);
// Weights are triangle areas in square pixels; a quantile does not work here
// because the source is so dense that most points weigh 0 after quantising.
topo = simplify(topo, MIN_AREA_PX);
const simplified = feature(topo, topo.objects.states);

// Coordinates are already pixels: no projection here.
const path = geoPath().digits(1);

const entries = simplified.features
  .map((f) => {
    const d = path(f);
    const [cx, cy] = path.centroid(f).map((n) => Math.round(n));
    return { slug: f.properties.slug, d, cx, cy };
  })
  .filter((e) => e.d)
  .sort((a, b) => a.slug.localeCompare(b.slug));

const body = entries
  .map((e) => `  { slug: '${e.slug}', cx: ${e.cx}, cy: ${e.cy}, d: '${e.d}' },`)
  .join('\n');

const out = `/* eslint-disable */
// GENERATED by scripts/generate-india-map.mjs. Do not edit by hand.
//
// India states and union territories, pre-projected (Mercator) into a
// ${WIDTH} x ${HEIGHT} viewBox. Boundaries: DataMeet India, States/Admin2
// (Ladakh and J&K as per the Survey of India map), CC BY 4.0,
// https://github.com/datameet/maps

export const INDIA_MAP_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}';

export interface IndiaStatePath {
  /** @neram/geo STATES slug. */
  slug: string;
  /** Centroid, for small-UT markers. */
  cx: number;
  cy: number;
  d: string;
}

export const INDIA_STATE_PATHS: IndiaStatePath[] = [
${body}
];
`;

writeFileSync(outPath, out);
console.log(`wrote ${entries.length} states, ${Math.round(out.length / 1024)} KB -> ${outPath}`);
